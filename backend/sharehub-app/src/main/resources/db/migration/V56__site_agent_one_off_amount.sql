-- ============================================================
-- ShareHub · 牵线费：一次性对价（ADR-027 §四 / TDD-A2 第 4 批）
--
-- 【为什么要一个「金额」列，而不是复用 share_rule.rate】
-- 牵线的对价是「把关系介绍过来」这个一次性动作，它不随 GMV 走 ——
-- `share_rule` 只有 rate（比例），没有金额。用比例表达一次性费用，
-- 就得再找一个基数去乘；而无论选 GMV 还是进场费，那个基数都是**编出来的**，
-- 日后没人说得清「这 500 块是怎么来的」。直接存金额，凭据就是它自己。
--
-- 【为什么挂在责任行上而不是伙伴上】
-- 同一个牵线人在不同站点介绍的价值不一样（旗舰商场 vs 街边店）。
-- 挂在伙伴上就只能有一个数，运营要么按最高的付、要么按最低的付，两种都不对。
--
-- 【只有 REFER 用得上】
-- 其余三档（出资/拓展/运维）是持续分成，走 share_rule 的比例。
-- 这一列留空对它们没有任何影响 —— 所以不给默认值：0 会被读成「明确不付」，
-- 而 NULL 才是「没配」。**没配 ≠ 0** 是本仓库反复强调的一条：
-- 前者该有人去配，后者是明确的不分，混为一谈就会静默少付。
-- ============================================================
SET NAMES utf8mb4;

ALTER TABLE loc_site_agent
  ADD COLUMN IF NOT EXISTS one_off_amount DECIMAL(18,2) NULL
  COMMENT '一次性对价（牵线费），签约时付；仅 REFER 用。NULL=没配，与 0（明确不付）不是一回事';
