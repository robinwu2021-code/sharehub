-- C 端「我的」页显示手机号：登录时存一份**真号的掩码**
--
-- 【缺口】验证码 / 密码登录时手里有归一化后的明文（ResolvedIdentity.phone），
-- 但全仓没有一处存它 —— usr_identity 只有 provider_uid（HMAC），明文随请求结束就没了。
-- 于是「我的」页、运营端用户 / 风控 / 黑白名单四张表的「手机」列只能如实出空
-- （此前更糟：拿 HMAC 的十六进制去掩码，冒充成 056****7c12）。
--
-- 【为什么只存掩码】显示用掩码就够了（用户看自己的号、运营核对尾号）。
-- 存可逆密文要引入密钥管理 —— V130 正是出于这个理由删掉了代理侧的 *_enc。
-- 掩码不可逆、不进唯一键、不做等值查询（ADR-030 §2.3 对 *_mask 的约定）。
--
-- 【存量】老用户没有明文可算，下次登录时补上（与手机号惰性重键同一时刻）。
-- 放在 usr_identity 而不是 usr_user：掩码属于「这条登录标识」，将来换绑手机号时跟着那一行走。
-- ════════════════════════════════════════════════════════════════════

ALTER TABLE usr_identity
    ADD COLUMN IF NOT EXISTS display_mask VARCHAR(32) NULL
        COMMENT '登录标识的显示掩码（手机号：前3后4；仅供显示，不可逆、不进唯一键）' AFTER union_key;
