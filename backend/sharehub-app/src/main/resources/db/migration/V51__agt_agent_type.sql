-- ============================================================
-- ShareHub · 代理商登记类型（ADR-027 §一 / 链条方案 A1）
--
-- 【解决什么】
-- 今天所有分润伙伴都叫「代理商」，而实际上有两种人：
--   · 代理商（AGENT）        出资 + 运维，按约定分润
--   · 城市合伙人（CITY_PARTNER）出资 + 拓展 + 运维 + 效果管理，包一片区域全责
-- 分不开的后果不是叫法难听，是**分润说不清按什么分** —— 两种人拿的钱性质不同。
--
-- 【为什么不同时建 md_agent_type】
-- ADR-027 的落地第 1 步里写了这张表（登记两种类型的「默认责任」与「默认费率」）。
-- 但**默认责任**要等 A2 的 `loc_site_agent`（伙伴 × 站点 × 责任）落地才有消费方，
-- 默认费率同理。现在建表只会多两行没人读的数据 —— 本项目已经有三处
-- 「有能力没消费方」的教训（时段倍率、适用范围、分润规则的 basis）。
-- 值域本来就要写进代码（后端校验、将来 ShareGenerator 按类型分支），
-- 展示名放前端的枚举映射即可，与本库其它枚举一致。
--
-- 【为什么不改菜单名】
-- ADR-027 §一 第 2 条：菜单保留「代理商管理」，只在档案里多一个字段。
-- 城市合伙人不是第二个实体 —— 分润、结算、提现、门户全套复用同一条链路，
-- 单开菜单会让人以为是两套数据。
-- ============================================================
SET NAMES utf8mb4;

ALTER TABLE agt_agent
  ADD COLUMN IF NOT EXISTS agent_type VARCHAR(24) NOT NULL DEFAULT 'AGENT'
  COMMENT '登记类型：AGENT 代理商 / CITY_PARTNER 城市合伙人（ADR-027）';

-- 存量一律 AGENT：默认值只对新行生效，已有行要显式回填。
-- 这里不猜「谁看起来像城市合伙人」—— 猜错会让分润按错的性质结算，
-- 由运营在档案页逐个改，改动可见、可追。
UPDATE agt_agent SET agent_type = 'AGENT' WHERE agent_type IS NULL OR agent_type = '';

ALTER TABLE agt_agent ADD KEY IF NOT EXISTS idx_agent_type (agent_type);
