-- ════════════════════════════════════════════════════════════════════
-- 提现：记下「审批人与放款人是否同一人」
--
-- 【2026-09-28 裁决】审批与放款是**两个动作**，按权限与流程配置，由管理员配置 ——
-- 不硬拦。方案见 docs/technical/方案-提现审批与放款分离.md。
--
-- 【为什么要落列，而不是每次拿 auditor_no 与 payer_no 比一下】
-- 「当时是不是同一人」是个**事实**，该在发生那一刻定格：
--   · auditor_no / payer_no 将来可能被归档清理，比不出来了；
--   · 对账单与审计导出要带这一列，而它们读的是行，不会临时去比。
-- 与分润 period 按结算时刻定格是同一个道理 —— 那处刚因为用「今天」错过一次
-- （见 RentOrderServiceImpl#publishSettled 的注释）。
--
-- 【REQUIRE 模式下这一列不会出现 1】
-- 三态里 REQUIRE（默认）直接拦住同一人放款，所以只有 WARN / OFF 才可能留下 1。
-- 关掉的是**拦截**，不是**记录** —— OFF 同样落 1，否则「当时允许了」这件事就没了。
--
-- 【存量行】历史提现没有这个判定，一律 0。不追溯计算：
-- auditor_no / payer_no 都在，真要查旧账随时能比，而把推算结果写成既成事实
-- 会让人以为那是当时判的。
-- ════════════════════════════════════════════════════════════════════

ALTER TABLE stl_withdrawal
    ADD COLUMN same_operator TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '审批人与放款人是否同一人（1=是）；REQUIRE 模式下不会出现 1'
        AFTER payer_name;
