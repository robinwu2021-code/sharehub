-- ============================================================
-- 权限码目录去掉 `agent:agent:create`
--
-- 【为什么刚加上又去掉】V124 补它是因为当时拆出了直连建档端点
-- （`POST /api/agent/agents`）并让它判这个码。而同一天裁决：
-- **代理商一律经入驻申请产生**（自助或代建录入 → 受理 → 审核），
-- 那条直连路径随之收掉 —— 于是这个码又没有任何端点认它了。
--
-- 【为什么必须跟着删】`iam_permission` 是「配角色时能勾什么」的来源。
-- 留着的后果不是报错，是**管理员勾了它却什么也没发生** ——
-- 他以为给某个角色开了「代理商 新增」，而没有任何端点认这个码。
-- 这与 V116 收拾的三个工单码是同一类，代价也一样：
-- 界面上明明有这一项、勾选也保存成功了，只是不生效。
--
-- 【安全性】它从 V124 到现在只存在了几个小时，`iam_role_perm` 里不会有人绑它；
-- 下面的 DELETE 会一并清掉（真有的话那条绑定本来也已失效）。
--
-- 【运营要在后台加代理商怎么办】用**代建录入**：`POST /api/agent/applies`
-- （`agent:apply:create`），走受理 → 审核，且审核人不能是录入人。
-- ============================================================

DELETE FROM iam_role_perm  WHERE perm_code = 'agent:agent:create';
DELETE FROM iam_permission WHERE code      = 'agent:agent:create';
