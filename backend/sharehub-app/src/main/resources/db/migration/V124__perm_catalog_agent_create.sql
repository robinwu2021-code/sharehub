-- ============================================================
-- 权限码目录补上 `agent:agent:create`
--
-- 【为什么现在才补】这个码本来是「声明未强制」：[功能权限清单] 里列着「代理商 增/改」
--   两个码，而后端建档与改档合用一个映射、一律判 `:update` ——
--   于是 `:create` 谁也不认，它只存在于文档里。
--   2026-09-26 拆开映射让它真正生效之后，问题**翻了个面**：
--   现在端点按它拒人，而 `iam_permission` 目录里没有它，
--   **管理员在角色勾选树上根本选不到它**。
--
--   这两种形态互为镜像，代价也一样：
--     · 有目录没强制 → 勾了等于没勾（V116 收拾的就是这一类）
--     · 有强制没目录 → 想开却开不了，而且看不出为什么
--   `PermCatalogCoverageTest` 盯的正是后者，本次由它抓到。
--
-- 【会不会把谁挡在外面】不会。生产持有代理写权限的只有 BD（`agent:*` 通配）
--   与 ADMIN（`*`），通配覆盖新码；补进目录只是让它**可被单独勾选**。
--
-- 【为什么不改 V100】那是已发布的迁移，改了 Flyway 会因校验和不符拒绝启动。
-- ============================================================

INSERT INTO iam_permission (code, name, module) VALUES
  ('agent:agent:create', '代理商 新增', 'agent')
ON DUPLICATE KEY UPDATE name = VALUES(name), module = VALUES(module);
