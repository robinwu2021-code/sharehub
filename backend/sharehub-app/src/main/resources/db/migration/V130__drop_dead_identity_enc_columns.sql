-- 删掉四个 *_enc 死列，并接受「pepper 不可轮换」这个事实
--
-- 【它们本来是干什么的】IdentifierHasher 的类注释写得很明确：
--   「轮换靠 *_enc 全表重算：解出明文 → 用新 pepper 重算 hash → 统一切 hash_ver。
--     这是 *_enc 必须可逆的**唯一理由**（ADR-030 §2.3）」
--
-- 【实际情况】那四列**全仓没有任何一处读或写**（grep setPhoneEnc / getPhoneEnc 零命中），
-- 生产上恒为 NULL。更彻底的是 `iam_employee` **压根没有 *_enc 列** ——
-- 员工那一侧从第一天起就没打算支持轮换。
--
-- 【所以真正的问题不是「有几列没人写」】而是：
-- **pepper 轮换是一条写在设计里、但这个系统做不到的操作。**
-- 一旦 pepper 泄露或合规要求更换，所有代理自然人与员工的身份哈希都算不回来 ——
-- 查不到人、登不进去，且没有恢复路径，只能重新收集每个人的手机号与邮箱。
-- 而 hash_ver 那句「轮换后据它判断哪些行还没重算」让它看起来是个常规运维动作。
-- **一个做不到却看起来能做的能力，比明确做不到更危险** —— 它会被写进应急预案。
--
-- 【为什么选择删列而不是把 *_enc 写起来】
-- 写起来要引入密钥管理（存哪、谁能解、怎么轮换密钥本身），
-- 为的是一个可能永不发生的操作；而 2026-09-27 生产上只有 2 个 principal、7 个员工，
-- 「全员重新登记」的代价几乎为零。规模小是现在处理它最便宜的理由，
-- 再过几个月就不是了。
--
-- 【代价，写清楚】删了之后 pepper **确定**不可轮换。真要换，等于：
--   ① 停写 → ② 通知所有代理与员工重新验证手机号/邮箱 → ③ 用新 pepper 重建 hash。
-- 这不是运维操作，是一次业务事件。IdentifierHasher 的类注释已同步改成这个说法，
-- 不再宣称「轮换靠 *_enc」。
--
-- 【幂等】用 IF EXISTS：这几列在 V47/V48 建的，但别的环境可能已经手工清过。
-- ════════════════════════════════════════════════════════════════════

ALTER TABLE agt_principal
    DROP COLUMN IF EXISTS phone_enc,
    DROP COLUMN IF EXISTS email_enc;

ALTER TABLE agt_apply
    DROP COLUMN IF EXISTS phone_enc,
    DROP COLUMN IF EXISTS email_enc;
