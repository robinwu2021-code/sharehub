package ai.neargo.sharehub.api.platform.dto;

/**
 * 代理商登记类型（ADR-027 §一）。
 *
 * <p>两者不是叫法之别：代理商出资 + 运维，城市合伙人还包拓展与效果管理，
 * <b>拿的钱性质不同</b> —— 分润说不清按什么分就是从这里开始的。
 *
 * <p>类型只定「他大体是哪种人」。「他在**这个站点**做了什么」由 A2 的
 * 「伙伴 × 站点 × 责任」表达；两者都要，否则「这个人在 A 站是介绍人、
 * 在 B 站是代理商」无处安放。
 *
 * <p><b>为什么在 {@code sharehub-api} 而不在 agent 域</b>：它被 loc 侧的
 * 「站点伙伴责任」读来做展示，是**跨域使用的词表**。词表一旦跨域就是契约的一部分 ——
 * 留在 agent 域会让 loc 反向依赖 agent，而站点在业务上不依赖代理商（平台直营的站点
 * 一个代理都没有），那个方向的依赖本身就是越界。
 */
public enum AgentType {

    /** 代理商：出资 + 运维，按约定分润。**缺省值**。 */
    AGENT,
    /** 城市合伙人：出资 + 拓展 + 运维 + 效果管理，包一片区域全责。 */
    CITY_PARTNER;

    /**
     * 宽松归一：认不出的一律落 {@link #AGENT}。
     *
     * <p>为什么不抛异常：存量行与外部调用都可能给空或旧值，而取不到类型时
     * 「当成代理商」是安全的缺省（它是更窄的责任集合）。
     * 但**不能默默落一个不认识的值** —— 那会让将来按类型分支的分润逻辑
     * 走到一条没写的分支，而那要到结算时才暴露。
     */
    public static AgentType of(String s) {
        return CITY_PARTNER.name().equalsIgnoreCase(s) ? CITY_PARTNER : AGENT;
    }
}
