// 全站常量（零硬编码约定：同一个值出现在**第二个文件**时就搬进来）。
//
// 判据不是"所有字面量都要进来"——那会变成一个谁也读不懂的数字仓库。
// 进来的标准是：它被多处引用，且**改它是一次产品决策**而不是一次局部调参。

/** 列表页默认每页条数。改这里全站生效；某页确有理由用别的值，在该页写明理由。 */
export const PAGE_SIZE = 10;

/**
 * 「一次取完、前端自己筛」的取数条数。
 *
 * ⚠️ **只用于设计上就有界的配置表**（银行字典、告警码、收费方案这类，量级几十到几百）。
 * 业务流水表（订单、分润明细、告警记录）**不许用它** —— 那些表会长到十万行，
 * 一次取完的后果不是慢，是浏览器卡死，而且在 mock 上永远复现不出来。
 *
 * 整理前页面里散着 `200`/`500`/`999`/`100`/`50` 六种取值共 38 处，
 * 没有任何一处说明为什么是那个数 —— 它们表达的其实是同一个意思。
 */
export const UNPAGED_SIZE = 500;

/** 搜索输入防抖（ms）。列表页关键词筛选统一用它。 */
export const SEARCH_DEBOUNCE_MS = 300;

/**
 * 默认货币（MENA 主市场，ADR-009）。
 * 多市场下由数据自带 `currency` 覆盖 —— 页面**不要**自己写 `"AED"` 字面量。
 */
export const DEFAULT_CURRENCY = "AED";

/**
 * 详情页「最近 N 条」子列表的条数（跟进记录、信用变动、干预记录…）。
 *
 * 与 {@link UNPAGED_SIZE} 不是一回事：那个的意思是「这张表设计上有界，一次取完」，
 * 这个的意思是「这张表会一直长，这里**只看最近的**」。两者混用会让人以为
 * 详情页展示的是全部 —— 它不是。
 */
export const RECENT_LIMIT = 50;

/** 全局搜索下拉的预览条数。不是分页，是「先给几条看看」。 */
export const SEARCH_PREVIEW_SIZE = 10;
