import { describe, expect, it } from "vitest";
import { looksLikePhone } from "./login-realm";

/**
 * 登录页按**输入形状**判账号池（2026-09-27 去掉两个 tab 之后的唯一判据）。
 *
 * 这条规则决定「向用户要口令还是要验证码」。判错的后果不是报错，是
 * **要错了凭据、登不进去**，而用户看到的只是一句登录失败 —— 所以它要被钉住。
 *
 * 规则本身不查库、不问后端，判的是字符形状而不是「这个账号存不存在」，
 * 因此不引入任何可枚举性。
 */
describe("looksLikePhone —— 只有手机号形状才走合作伙伴（验证码）那条路", () => {
  it.each([
    ["13800138000", "国内 11 位"],
    ["+971501234567", "带国际区号"],
    ["971501234567", "不带 +"],
    ["+971 50 123 4567", "带空格"],
    ["+971-50-123-4567", "带连字符"],
  ])("%s 判为手机号（%s）", (v) => {
    expect(looksLikePhone(v)).toBe(true);
  });

  it.each([
    ["E1005", "员工号带字母前缀"],
    ["admin", "共享口令闸的账号"],
    ["ops@sharehub.ae", "邮箱"],
    ["", "空"],
    ["   ", "只有空白"],
  ])("%s 不判为手机号（%s）", (v) => {
    expect(looksLikePhone(v)).toBe(false);
  });

  /*
   * 要求 7 位以上，而不是「只要是数字」。
   *
   * 不设下限的话，用户打员工号的过程中 `1`、`13` 会一路被判成手机号 ——
   * 提示行跟着抖（「用验证码登录」闪一下又变回去），而他其实在输员工号。
   * 这不是理论问题：默认值是 `admin`，清空重打的第一个字符就会触发。
   */
  it.each(["1", "13", "138001"])("%s 位数不够，不判为手机号", (v) => {
    expect(looksLikePhone(v)).toBe(false);
  });

  /* 上限 15 位是 E.164 的上界；超了说明输错了，不该当手机号送去发验证码。 */
  it("超过 15 位不判为手机号", () => {
    expect(looksLikePhone("1234567890123456")).toBe(false);
  });

  /*
   * ⚠️ 这条规则依赖当前的标识约定：员工号带字母前缀（E1005）、邮箱带 @。
   * 哪天员工号变成纯数字，它会把员工误判成合作伙伴 —— 下面这条把那个前提写成断言，
   * 让约定变了的时候这里先红，而不是等用户登不进去。
   */
  it("前提：员工标识都不是纯数字（约定变了要先在这里红）", () => {
    for (const staffId of ["E1001", "E1007", "admin", "ops@sharehub.ae"]) {
      expect(looksLikePhone(staffId)).toBe(false);
    }
  });
});
