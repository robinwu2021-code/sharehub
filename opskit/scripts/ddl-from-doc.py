#!/usr/bin/env python3
"""从设计文档 21/04 抽取某一节的 MySQL DDL，生成三方言 Flyway 脚本。

用法：scripts/ddl-from-doc.py "### 3.3 流程" process V1__process_baseline
MySQL 版逐字取自文档；PG / H2 按固定规则转换（与 21/04 §四 一致）：
自增 → IDENTITY · JSON → JSONB(PG) · TINYINT → SMALLINT(PG) · MEDIUMTEXT → TEXT(PG) / CLOB(H2) ·
DECIMAL → NUMERIC(PG) · TEXT 保持 · 表内 KEY → 表外 CREATE INDEX（索引名加表名前缀，两库索引名全库唯一）。
文档改了就重新生成，保证代码与文档是同一份。"""
import io, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
doc_path = os.path.join(here, '..', '..', 'docs', 'technical', 'v4', '16-工作流与工单', '21-设计方案-重梳', '04-数据库设计.md')
heading, module, name = sys.argv[1], sys.argv[2], sys.argv[3]
doc = io.open(doc_path, encoding='utf-8').read()
start = doc.index(heading)
nxt = doc.find('\n### ', start + len(heading))
sec = doc[start: nxt if nxt > 0 else len(doc)]
mysql = sec[sec.index('```sql') + 6: sec.index('```', sec.index('```sql') + 6)].strip() + '\n'

def convert(sql, pg):
    out = []
    for stmt in [s.strip() for s in sql.split(';') if 'CREATE TABLE' in s]:
        stmt = re.sub(r'--[^\n]*', '', stmt)
        m = re.search(r'CREATE TABLE (\w+) \((.*)\)\s*$', stmt, re.S)
        table, body = m.group(1), m.group(2)
        parts, depth, cur = [], 0, ''
        for ch in body:
            if ch == '(':
                depth += 1
            if ch == ')':
                depth -= 1
            if ch == ',' and depth == 0:
                parts.append(cur.strip()); cur = ''
            else:
                cur += ch
        if cur.strip():
            parts.append(cur.strip())
        cols, idx = [], []
        for p in parts:
            p = ' '.join(p.split())
            if not p:
                continue
            km = re.match(r'UNIQUE KEY (\w+) \((.*)\)$', p)
            if km:
                cols.append(f'CONSTRAINT {table}_{km.group(1)} UNIQUE ({km.group(2)})'); continue
            km = re.match(r'KEY (\w+) \((.*)\)$', p)
            if km:
                idx.append(f'CREATE INDEX {table}_{km.group(1)} ON {table} ({km.group(2)});'); continue
            p = p.replace('BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            if pg:
                p = re.sub(r'\bJSON\b', 'JSONB', p); p = re.sub(r'\bTINYINT\b', 'SMALLINT', p)
                p = re.sub(r'\bMEDIUMTEXT\b', 'TEXT', p); p = re.sub(r'\bDECIMAL\b', 'NUMERIC', p)
            else:
                p = re.sub(r'\bMEDIUMTEXT\b', 'CLOB', p)
            cols.append(p)
        out.append(f'CREATE TABLE {table} (\n  ' + ',\n  '.join(cols) + '\n);')
        out.extend(idx)
    return '\n'.join(out) + '\n'

hdr = f'-- 由 scripts/ddl-from-doc.py 从 21/04「{heading.strip("# ")}」生成，勿手改；改文档后重新生成。\n'
base = os.path.join(here, '..', module, f'{module}-store', 'src', 'main', 'resources', 'db', module)
for vendor, text in (('mysql', mysql), ('postgresql', convert(mysql, True)), ('h2', convert(mysql, False))):
    os.makedirs(os.path.join(base, vendor), exist_ok=True)
    io.open(os.path.join(base, vendor, name + '.sql'), 'w', encoding='utf-8').write(hdr + text)
    print(vendor, text.count('CREATE TABLE'), 'tables')
