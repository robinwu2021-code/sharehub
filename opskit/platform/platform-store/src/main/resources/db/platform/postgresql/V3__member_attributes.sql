-- 成员属性定义（21/07 O1-12），与 MySQL 版同结构。
CREATE TABLE plat_member_attr (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL DEFAULT '',
  attr_key VARCHAR(64) NOT NULL,
  name JSONB NOT NULL,
  value_labels JSONB NOT NULL,
  updated_by VARCHAR(80) NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_member_attr_uk_attr UNIQUE (account_id, workspace_id, attr_key)
);
