-- 平台基线（21/04 §3.1）。MySQL 版逐字取自设计文档；PG / H2 版由同一份按固定规则转换：
-- 自增 → IDENTITY · JSON → JSONB(PG) · TINYINT → SMALLINT(PG) · MEDIUMTEXT → TEXT(PG) / CLOB(H2) · 表内 KEY → 表外 CREATE INDEX（索引名加表名前缀，两库索引名全库唯一）。
CREATE TABLE plat_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  name VARCHAR(128) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  plan VARCHAR(32) NOT NULL DEFAULT 'STANDARD',
  quotas JSON NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_account_uk_account UNIQUE (account_id)
);
CREATE TABLE plat_workspace (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  name VARCHAR(128) NOT NULL,
  external_ref VARCHAR(128) NULL,
  default_zone VARCHAR(64) NOT NULL DEFAULT 'UTC',
  default_locale VARCHAR(16) NOT NULL DEFAULT 'zh',
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_workspace_uk_ws UNIQUE (workspace_id),
  CONSTRAINT plat_workspace_uk_ext UNIQUE (account_id, external_ref)
);
CREATE TABLE plat_app (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  app_id VARCHAR(32) NOT NULL,
  name VARCHAR(128) NOT NULL,
  credential_hash VARCHAR(128) NOT NULL,
  credential_hint VARCHAR(8) NULL,
  all_workspaces TINYINT NOT NULL DEFAULT 0,
  callback_base_url VARCHAR(512) NULL,
  signing_secret_enc VARCHAR(512) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_app_uk_app UNIQUE (app_id),
  CONSTRAINT plat_app_uk_cred UNIQUE (credential_hash)
);
CREATE TABLE plat_app_workspace (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  CONSTRAINT plat_app_workspace_uk_app_ws UNIQUE (app_id, workspace_id)
);
CREATE TABLE plat_idp (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  issuer VARCHAR(256) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  config JSON NOT NULL,
  claim_mapping JSON NOT NULL,
  jit_enabled TINYINT NOT NULL DEFAULT 1,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_idp_uk_issuer UNIQUE (issuer)
);
CREATE TABLE plat_member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  member_id VARCHAR(32) NOT NULL,
  external_ref VARCHAR(128) NOT NULL,
  display_name VARCHAR(128) NULL,
  attrs JSON NULL,
  scopes JSON NULL,
  source VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  last_seen_at_ms BIGINT NULL,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_member_uk_member UNIQUE (workspace_id, member_id),
  CONSTRAINT plat_member_uk_ext UNIQUE (workspace_id, external_ref)
);
CREATE TABLE plat_group (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  group_code VARCHAR(64) NOT NULL,
  name JSON NOT NULL,
  kind VARCHAR(16) NOT NULL DEFAULT 'TEAM',
  claim_timeout_sec INT NULL,
  order_by VARCHAR(16) NULL,
  external_ref VARCHAR(128) NULL,
  source VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_group_uk_group UNIQUE (workspace_id, group_code)
);
CREATE TABLE plat_group_member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id VARCHAR(32) NOT NULL,
  group_code VARCHAR(64) NOT NULL,
  member_id VARCHAR(32) NOT NULL,
  source VARCHAR(16) NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_group_member_uk_gm UNIQUE (workspace_id, group_code, member_id)
);
CREATE INDEX plat_group_member_idx_member ON plat_group_member (workspace_id, member_id);
CREATE TABLE plat_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL DEFAULT '',
  role_code VARCHAR(64) NOT NULL,
  name JSON NOT NULL,
  permissions JSON NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_role_uk_role UNIQUE (account_id, workspace_id, role_code)
);
CREATE TABLE plat_role_binding (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id VARCHAR(32) NOT NULL,
  role_code VARCHAR(64) NOT NULL,
  principal VARCHAR(80) NOT NULL,
  source VARCHAR(16) NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_role_binding_uk_binding UNIQUE (workspace_id, role_code, principal)
);
CREATE INDEX plat_role_binding_idx_principal ON plat_role_binding (workspace_id, principal);
CREATE TABLE plat_calendar (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL DEFAULT '',
  calendar_code VARCHAR(64) NOT NULL,
  zone VARCHAR(64) NOT NULL,
  weekly JSON NOT NULL,
  holidays JSON NULL,
  updated_by VARCHAR(80) NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_calendar_uk_cal UNIQUE (account_id, workspace_id, calendar_code)
);
CREATE TABLE plat_webhook_subscription (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL DEFAULT '',
  app_id VARCHAR(32) NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  url VARCHAR(512) NOT NULL,
  enabled TINYINT NOT NULL DEFAULT 1,
  CONSTRAINT plat_webhook_subscription_uk_sub UNIQUE (account_id, workspace_id, app_id, event_type, url)
);
CREATE TABLE plat_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  idem_key VARCHAR(160) NOT NULL,
  payload CLOB NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  next_at_ms BIGINT NOT NULL,
  done_at_ms BIGINT NULL,
  failed TINYINT NOT NULL DEFAULT 0,
  last_error VARCHAR(512) NULL,
  created_at_ms BIGINT NOT NULL,
  CONSTRAINT plat_outbox_uk_idem UNIQUE (workspace_id, event_type, idem_key)
);
CREATE INDEX plat_outbox_idx_due ON plat_outbox (done_at_ms, failed, next_at_ms);
CREATE TABLE plat_webhook_delivery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL,
  outbox_id BIGINT NOT NULL,
  subscription_id BIGINT NOT NULL,
  attempt INT NOT NULL,
  http_status INT NULL,
  latency_ms INT NULL,
  error VARCHAR(512) NULL,
  at_ms BIGINT NOT NULL
);
CREATE INDEX plat_webhook_delivery_idx_outbox ON plat_webhook_delivery (outbox_id, attempt);
CREATE INDEX plat_webhook_delivery_idx_ws_at ON plat_webhook_delivery (workspace_id, at_ms);
CREATE TABLE plat_idempotency (
  caller VARCHAR(80) NOT NULL,
  idem_key VARCHAR(128) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  http_status INT NOT NULL,
  response_body JSON NULL,
  at_ms BIGINT NOT NULL,
  PRIMARY KEY (caller, idem_key)
);
CREATE INDEX plat_idempotency_idx_at ON plat_idempotency (at_ms);
CREATE TABLE plat_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  workspace_id VARCHAR(32) NOT NULL DEFAULT '',
  actor VARCHAR(80) NOT NULL,
  action VARCHAR(64) NOT NULL,
  target VARCHAR(160) NOT NULL,
  detail JSON NULL,
  at_ms BIGINT NOT NULL
);
CREATE INDEX plat_audit_log_idx_ws_at ON plat_audit_log (account_id, workspace_id, at_ms);
